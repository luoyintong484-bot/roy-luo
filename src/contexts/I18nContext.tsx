function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const stored = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (stored && ["zh", "zh-TW", "en"].includes(stored)) return stored;
  } catch {}
  const lang = navigator.language;
  if (lang.startsWith("zh-TW") || lang.startsWith("zh-HK")) return "zh-TW";
  if (lang.startsWith("zh")) return "zh";
  return "en";
}

interface I18nContextType {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: "en",
  setLocale: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getStoredLocale);

  const { data: serverTranslations } = trpc.i18n.getTranslations.useQuery(
    { locale },
    { staleTime: Infinity }
  );

  const [translations, setTranslations] = useState<Record<string, string>>({});

  useEffect(() => {
    const navDict = NAV_TRANSLATIONS[locale] || NAV_TRANSLATIONS["en"];
    if (serverTranslations) {
      setTranslations({ ...navDict, ...serverTranslations });
    } else {
      setTranslations(navDict);
    }
  }, [serverTranslations, locale]);

  const setLocale = useCallback((newLocale: Locale) => {
    setLocaleState(newLocale);
    try { localStorage.setItem(STORAGE_KEY, newLocale); } catch {}
  }, []);

  const t = useCallback(
    (key: string) => translations[key] ?? key,
    [translations]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
