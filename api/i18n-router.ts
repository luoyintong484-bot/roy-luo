// Map new locale codes to legacy translation keys
function mapLocale(locale: string): string {
  if (locale === "zh") return "zh-CN";
  if (locale === "en") return "en";
  return locale;
}

export const i18nRouter = createRouter({
  getTranslations: publicQuery
    .input(z.object({ locale: z.string() }))
    .query(async ({ input }) => {
      const key = mapLocale(input.locale);
      return translations[key] ?? translations["zh-CN"];
    }),

  listLocales: publicQuery.query(() => {
    return [
      { code: "zh", name: "中文" },
      { code: "en", name: "English" },
    ];
  }),
});
